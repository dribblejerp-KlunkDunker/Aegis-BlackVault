/**
 * Upgrades a database created at an older schema version and checks that:
 *  - every migration produces exactly the schema Room expects (validated against the exported JSON),
 *  - existing rows survive, and new columns get the documented defaults,
 *  - the migrated file opens with the real Room database and the governance features work on it.
 *
 * Schemas live in app/schemas/ (5.json is generated by Room; 3.json and 4.json are the earlier shapes).
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class MigrationTest {

    @get:Rule
    val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        AegisDatabase::class.java
    )

    private val dbName = "migration-test.db"

    private fun insertV3Rows(db: SupportSQLiteDatabase) {
        val subject = ContentValues().apply {
            put("id", LEGACY_ID)
            put("stixId", "identity--legacy")
            put("handle", LEGACY_HANDLE)
            put("codeId", "LEG-1")
            put("alias", "Legacy")
            put("cluster", "pre-v4")
            put("loc", "Unknown")
            put("lat", 0.0)
            put("lon", 0.0)
            put("utcOffset", 0)
            put("troughWindowLabel", "")
            put("burrowsDelta", 0.0)
            put("styloMatch", 0.0)
            put("mattrScore", 0.0)
            listOf(
                "oceanJson",
                "darkTriadJson",
                "threatMetricsJson",
                "zScoresJson",
                "insightsJson",
                "linguisticProfileJson"
            ).forEach { put(it, "{}") }
            listOf("hourlyBinsJson", "githubReposJson", "huggingFaceModelsJson", "artifactsJson").forEach { put(it, "[]") }
            put("frontStageQuote", "hello")
            put("backStageQuote", "world")
            put("healedPatchId", "")
            put("provSha256", "a".repeat(64))
            put("updatedAt", 1_700_000_000_000L)
        }
        db.insert("subject_profiles", SQLiteDatabase.CONFLICT_FAIL, subject)

        val artifact = ContentValues().apply {
            put("entityId", "art-legacy-1")
            put("subjectId", LEGACY_ID)
            put("subjectHandle", LEGACY_HANDLE)
            put("platform", "GITHUB")
            put("sourceUri", "https://example.invalid/legacy")
            put("postedTimestampIso", "2023-11-14T22:13:20Z")
            put("utcHour", 22)
            put("rawPayloadText", "legacy payload")
            put("rawDomSignature", "")
            put("lexicalMarkersCsv", "")
            put("sentimentScore", 50)
            put("provSha256", "b".repeat(64))
            put("ingestedAtMillis", 1_700_000_000_000L)
        }
        db.insert("raw_social_media_entities", SQLiteDatabase.CONFLICT_FAIL, artifact)
    }

    private fun SupportSQLiteDatabase.single(sql: String): List<Any?> = query(sql).use { c ->
        assertTrue("expected one row for: $sql", c.moveToFirst())
        val row = (0 until c.columnCount).map { i ->
            when (c.getType(i)) {
                android.database.Cursor.FIELD_TYPE_INTEGER -> c.getLong(i)
                android.database.Cursor.FIELD_TYPE_NULL -> null
                else -> c.getString(i)
            }
        }
        assertTrue("expected exactly one row for: $sql", !c.moveToNext())
        row
    }

    @Test
    fun `v3 to v4 keeps subjects and marks them unverified with unknown provenance`() {
        helper.createDatabase(dbName, 3).use { insertV3Rows(it) }

        val v4 = helper.runMigrationsAndValidate(dbName, 4, true, AegisDatabase.MIGRATION_3_4)

        val row = v4.single("SELECT handle, consentStatus, corpusWordCount, dataProvenance FROM subject_profiles")
        assertEquals(listOf<Any?>(LEGACY_HANDLE, "UNVERIFIED", 0L, "UNKNOWN (pre-v4)"), row)
        v4.close()
    }

    @Test
    fun `v3 to v6 in one upgrade keeps every row and adds governance columns`() {
        helper.createDatabase(dbName, 3).use { insertV3Rows(it) }

        val v5 = helper.runMigrationsAndValidate(dbName, 6, true, *AegisDatabase.ALL_MIGRATIONS)

        assertEquals(
            listOf<Any?>("UNVERIFIED", "", 0L, 0L),
            v5.single("SELECT consentStatus, consentMethod, consentRecordedAt, consentExpiresAt FROM subject_profiles")
        )
        // Legacy artifacts have no chain of custody; the columns are present but honestly empty.
        assertEquals(
            listOf<Any?>("legacy payload", "", 0L, 0L, "", ""),
            v5.single(
                "SELECT rawPayloadText, sourceUrl, fetchedAtMillis, httpStatus, rawResponseSha256, connectorRunId " +
                    "FROM raw_social_media_entities"
            )
        )
        assertEquals(listOf<Any?>(0L), v5.single("SELECT COUNT(*) FROM audit_log"))
        // The append-only triggers are installed by the migration itself.
        assertEquals(
            listOf<Any?>(2L),
            v5.single("SELECT COUNT(*) FROM sqlite_master WHERE type = 'trigger' AND tbl_name = 'audit_log'")
        )
        // Schema v6: everything that existed lands in the default project.
        assertEquals(
            listOf<Any?>(ProjectEntity.DEFAULT_ID, ProjectEntity.DEFAULT_NAME, 0L, 0L),
            v5.single(
                "SELECT p.id, p.name, p.retentionDays, p.allowCrossProjectLinks FROM projects p"
            )
        )
        assertEquals(listOf<Any?>(ProjectEntity.DEFAULT_ID), v5.single("SELECT projectId FROM subject_profiles"))
        v5.close()
    }

    @Test
    fun `v5 to v6 moves subjects and triplets into the default project`() {
        helper.createDatabase(dbName, 3).use { insertV3Rows(it) }
        helper.runMigrationsAndValidate(dbName, 5, true, AegisDatabase.MIGRATION_3_4, AegisDatabase.MIGRATION_4_5).use { db ->
            db.execSQL(
                "INSERT INTO knowledge_triplets (id, subjectHandle, predicate, objectNode, nodeCategory, confidence, provSha256, timestamp) " +
                    "VALUES ('t-1', '$LEGACY_HANDLE', 'USES', 'kotlin', 'SKILL', 0.9, '', 1)"
            )
        }
        val v6 = helper.runMigrationsAndValidate(dbName, 6, true, AegisDatabase.MIGRATION_5_6)
        assertEquals(listOf<Any?>(ProjectEntity.DEFAULT_ID), v6.single("SELECT projectId FROM knowledge_triplets"))
        assertEquals(listOf<Any?>(ProjectEntity.DEFAULT_ID), v6.single("SELECT projectId FROM subject_profiles"))
        v6.close()
    }

    @Test
    fun `a migrated file opens with the real database and governance works on it`() = runTest {
        // Room's own builder runs the last step (v5 -> v6), exactly as on a user's device.
        helper.createDatabase(dbName, 3).use { insertV3Rows(it) }
        helper.runMigrationsAndValidate(
            dbName,
            5,
            true,
            AegisDatabase.MIGRATION_3_4,
            AegisDatabase.MIGRATION_4_5
        ).close()

        val context = ApplicationProvider.getApplicationContext<Context>()
        val db = Room.databaseBuilder(context, AegisDatabase::class.java, dbName)
            .addMigrations(*AegisDatabase.ALL_MIGRATIONS)
            .addCallback(AegisDatabase.AUDIT_TRIGGERS_CALLBACK)
            .allowMainThreadQueries()
            .build()
        helper.closeWhenFinished(db)
        val dao = db.aegisDao()
        val repository = AegisRepository(dao)

        assertEquals(1, dao.observeRawSocialEntitiesForSubject(LEGACY_ID).first().size)

        repository.audit(AuditAction.CONSENT_CHANGED, LEGACY_ID, "UNVERIFIED -> SELF via SELF_DECLARED")
        assertTrue(repository.verifyAuditChain().intact)
        val sql = db.openHelper.writableDatabase
        assertThrows(Exception::class.java) { sql.execSQL("DELETE FROM audit_log") }

        assertTrue(repository.deleteSubject(LEGACY_ID, LEGACY_HANDLE, reason = "migration test"))
        assertTrue(dao.observeRawSocialEntitiesForSubject(LEGACY_ID).first().isEmpty())
        assertEquals(AuditAction.SUBJECT_DELETED.name, dao.lastAuditEntry()!!.action)
        assertTrue(repository.verifyAuditChain().intact)
    }

    @Test
    fun `committed schema for the current version matches the compiled database`() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val db = Room.inMemoryDatabaseBuilder(context, AegisDatabase::class.java).allowMainThreadQueries().build()
        val (version, compiledHash) = db.openHelper.readableDatabase.let { sql ->
            sql.version to sql.query("SELECT identity_hash FROM room_master_table WHERE id = 42").use { c ->
                c.moveToFirst()
                c.getString(0)
            }
        }
        db.close()
        val json = InstrumentationRegistry.getInstrumentation().context.assets
            .open("com.example.data.AegisDatabase/$version.json").bufferedReader().use { it.readText() }
        val committedHash = org.json.JSONObject(json).getJSONObject("database").getString("identityHash")
        assertEquals(
            "app/schemas/com.example.data.AegisDatabase/$version.json is stale; Room's identity hash is $compiledHash",
            compiledHash,
            committedHash
        )
    }

    private companion object {
        const val LEGACY_ID = "subj-legacy"
        const val LEGACY_HANDLE = "legacy_handle"
    }
}
